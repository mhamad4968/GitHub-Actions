#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BUILD =
  process.env.JIKKOU_YOSAN_V2_BUILD || "2026-07-21-ver02-phase5-m2m4";
const moduleDirectory = path.join(root, "scripts/lib/jikkou-yosan-v2");
// Tests may redirect the bundle (e.g. to a temp file) so parallel test files
// never race on the committed artifact. customize/736 stays forbidden below.
const outputPath = process.env.JIKKOU_YOSAN_V2_OUTPUT
  ? path.resolve(root, process.env.JIKKOU_YOSAN_V2_OUTPUT)
  : path.join(root, "customize/jikkou-yosan-v2-app1/desktop.js");
const sourceNames = [
  "decimal.mjs",
  "calc.mjs",
  "keys.mjs",
  "lock.mjs",
  "guard.mjs",
  "planner.mjs",
  "conflict.mjs",
  "executor.mjs",
  "client-adapter.mjs",
  "save-model.mjs",
  "ui-model.mjs",
  "projection.mjs",
  "contract-salary-model.mjs",
  "detail-block-model.mjs",
  "actuals-matrix.mjs",
  "version-series-model.mjs",
  "version-copy-model.mjs",
];

function stripEsm(source, name) {
  const stripped = source
    .replace(/^import\s+[\s\S]*?;\s*$/gm, "")
    .replace(/^export\s+(?=(?:const|let|var|function|class|async\s+function)\b)/gm, "")
    .replace(/^export\s*\{[\s\S]*?\};?\s*$/gm, "");
  if (/^\s*(?:import|export)\b/m.test(stripped)) {
    throw new Error(`${name}: unsupported ESM syntax remains after stripping`);
  }
  return stripped.trim();
}

const protectedDirectory = path.resolve(root, "customize/736");
if (path.resolve(outputPath).startsWith(`${protectedDirectory}${path.sep}`)) {
  throw new Error("Ver.02 build must never write customize/736");
}

const moduleSources = sourceNames.map((name) =>
  stripEsm(readFileSync(path.join(moduleDirectory, name), "utf8"), name),
);
const uiSource = readFileSync(
  path.join(root, "customize/jikkou-yosan-v2-app1/desktop.ui.js"),
  "utf8",
).trimEnd();

const output = `/**
 * 実行予算書作成支援ツールver02 — BUILD ${BUILD}
 * Generated by scripts/jikkou-yosan-v2-build-desktop.mjs
 */
(function () {
  "use strict";
  const BUILD = ${JSON.stringify(BUILD)};

${moduleSources.join("\n\n")}

${uiSource}
})();
`;

writeFileSync(outputPath, output, "utf8");
execFileSync(process.execPath, ["--check", outputPath], { stdio: "inherit" });
// #S1 (2026-07-21 夕反省承認): 束ねでモジュール私有ヘルパーが同名衝突すると
// node --check では通るため、push ゲートまで検知が遅れる。build 直後に lint する。
// --config 明示: テストが出力を repo 外 (%TEMP%) に逃がしても flat config を解決できるように。
execFileSync(
  process.execPath,
  [
    path.join(root, "node_modules/eslint/bin/eslint.js"),
    "--config",
    path.join(root, "eslint.config.js"),
    "--no-warn-ignored",
    outputPath,
  ],
  { stdio: "inherit", cwd: root },
);
console.log(`Wrote ${outputPath}`);
